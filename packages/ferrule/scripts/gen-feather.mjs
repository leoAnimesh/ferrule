#!/usr/bin/env node
// Writes src/feather-data.ts and LICENSE-feather from the feather-icons devDependency. Rerun after updating it.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.dirname(require.resolve('feather-icons/package.json'));
const { version } = JSON.parse(fs.readFileSync(path.join(source, 'package.json'), 'utf8'));
const icons = JSON.parse(fs.readFileSync(path.join(source, 'dist/icons.json'), 'utf8'));

const attrs = (text) => Object.fromEntries([...text.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const points = (text) => text.trim().split(/[\s,]+/).map(Number);
const polyline = (list, close) => {
  let d = `M${list[0]} ${list[1]}`;
  for (let i = 2; i < list.length; i += 2) d += `L${list[i]} ${list[i + 1]}`;
  return close ? `${d}Z` : d;
};
/** Every Feather shape as path data, so the runtime only has to read one format. */
export function toPath(svg) {
  let d = '';
  for (const [, tag, rest] of svg.matchAll(/<(\w+)([^>]*)>/g)) {
    const a = attrs(rest);
    const n = (key) => Number(a[key] ?? 0);
    if (tag === 'path') d += a.d;
    else if (tag === 'line') d += `M${n('x1')} ${n('y1')}L${n('x2')} ${n('y2')}`;
    else if (tag === 'polyline') d += polyline(points(a.points), false);
    else if (tag === 'polygon') d += polyline(points(a.points), true);
    else if (tag === 'circle' || tag === 'ellipse') {
      const rx = tag === 'circle' ? n('r') : n('rx');
      const ry = tag === 'circle' ? n('r') : n('ry');
      d += `M${n('cx') - rx} ${n('cy')}A${rx} ${ry} 0 1 0 ${n('cx') + rx} ${n('cy')}A${rx} ${ry} 0 1 0 ${n('cx') - rx} ${n('cy')}Z`;
    } else if (tag === 'rect') {
      const [x, y, w, h, r] = [n('x'), n('y'), n('width'), n('height'), Math.max(n('rx'), n('ry'))];
      d += r
        ? `M${x + r} ${y}H${x + w - r}A${r} ${r} 0 0 1 ${x + w} ${y + r}V${y + h - r}A${r} ${r} 0 0 1 ${x + w - r} ${y + h}H${x + r}A${r} ${r} 0 0 1 ${x} ${y + h - r}V${y + r}A${r} ${r} 0 0 1 ${x + r} ${y}Z`
        : `M${x} ${y}H${x + w}V${y + h}H${x}Z`;
    } else throw new Error(`unknown Feather shape <${tag}>`);
  }
  return d;
}

const body = Object.entries(icons).map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(toPath(svg))},`).join('\n');
fs.writeFileSync(path.join(ROOT, 'src/feather-data.ts'), `// Generated by scripts/gen-feather.mjs from feather-icons ${version}. MIT, see LICENSE-feather. Do not edit.\nexport const FEATHER = {\n${body}\n} as const;\n`);
fs.copyFileSync(path.join(source, 'LICENSE'), path.join(ROOT, 'LICENSE-feather'));
console.log(`feather-icons ${version}: ${Object.keys(icons).length} icons`);
